function build_sensors(path)
% Assemble the M2 inline current sensors and the AS5600 in an empty subsystem.
% Firmware reference: firmware/foc/main/main.c at c20fad4.
add_block('simulink/Sources/In1', [path '/iUVW_A'], ...
    'Port', '1', 'Position', [25 100 55 114]);
add_block('simulink/Sources/In1', [path '/theta_m_rad'], ...
    'Port', '2', 'Position', [25 270 55 284]);
add_block('simulink/Discrete/Zero-Order Hold', [path '/Hold phase currents'], ...
    'SampleTime', 'Ts_ctrl', 'Position', [105 82 167 132]);
add_block('simulink/Discrete/Zero-Order Hold', [path '/Hold rotor angle'], ...
    'SampleTime', 'Ts_ctrl', 'Position', [105 252 167 302]);

analog = strjoin({ ...
    'function [mv_uv, zero_mv] = sense(iUVW_A, b_u_mV, b_v_mV, R_shunt, sense_gain, sense_wiring_sign)', ...
    '% The physical shunt polarity is independent of the software sign correction.', ...
    'zero_mv = [b_u_mV; b_v_mV];', ...
    'amps_uv = [iUVW_A(1); iUVW_A(2)];', ...
    'mv_uv = zero_mv + sense_wiring_sign * (1000 * R_shunt * sense_gain) * amps_uv;', ...
    'end'}, newline);
mf_chart(path, 'U V shunts and INA199', [220 65 385 146], analog, ...
    {'b_u_mV', 'b_v_mV', 'R_shunt', 'sense_gain', 'sense_wiring_sign'});

adc = strjoin({ ...
    'function [mv_uv, offset_uv] = adc(pin_uv, pin_zero, adc_bits, adc_range_mV)', ...
    '% Running samples and the stationary zero calibration use the same ADC model.', ...
    'last_code = 2^adc_bits - 1;', ...
    'mv_uv = adc_read_mv(pin_uv, last_code, adc_range_mV);', ...
    'offset_uv = adc_read_mv(pin_zero, last_code, adc_range_mV);', ...
    'end', ...
    'function mv = adc_read_mv(pin_mv, last_code, range_mv)', ...
    '% The two one-shot reads see the same held voltage. Their integer mean is raw.', ...
    'clipped_mv = min(max(pin_mv, 0), range_mv);', ...
    'raw = floor(clipped_mv * (last_code/range_mv) + 0.5);', ...
    '% main.c:525, without a chip-specific calibration curve.', ...
    'mv = floor((raw * range_mv) / last_code);', ...
    'end'}, newline);
mf_chart(path, 'ADC1 two reads and mV', [436 65 612 146], adc, ...
    {'adc_bits', 'adc_range_mV'});

convert = strjoin({ ...
    'function uv_mA = convert(mv_uv, offset_uv, R_shunt, sense_gain, sense_sign, unipolar_threshold_mV)', ...
    '% A stationary, disabled motor gives identical readings throughout zero calibration.', ...
    'delta_mv = mv_uv - offset_uv;', ...
    'if all(offset_uv < unipolar_threshold_mV)', ...
    '    delta_mv = max(delta_mv, 0);', ...
    'end', ...
    'uv_mA = sense_sign * delta_mv / (R_shunt * sense_gain);', ...
    'end'}, newline);
mf_chart(path, 'Remove offsets and set sign', [663 65 868 146], convert, ...
    {'R_shunt', 'sense_gain', 'sense_sign', 'unipolar_threshold_mV'});
add_block('simulink/Sinks/Out1', [path '/uv_mA'], ...
    'Port', '1', 'Position', [939 100 969 114]);

angle = strjoin({ ...
    'function raw = encoder(theta_m_rad, s_enc, p_pairs, theta_off, enc_bits)', ...
    '% Sensor mounting is the inverse of the calibrated mech_to_elec relationship.', ...
    'angle_rad = mod(s_enc * (theta_m_rad - theta_off / p_pairs), 2*pi);', ...
    '% Select the angular bin that contains the actual mechanical angle.', ...
    'bins = 2^enc_bits;', ...
    'raw = min(bins-1, floor(angle_rad * (bins/(2*pi))));', ...
    'end'}, newline);
mf_chart(path, 'AS5600 angle to code', [220 235 418 314], angle, ...
    {'s_enc', 'p_pairs', 'theta_off', 'enc_bits'});
add_block('simulink/Math Operations/Gain', [path '/Raw code to radians'], ...
    'Gain', '2*pi/(2^enc_bits)', 'Position', [485 250 568 303]);
add_block('simulink/Sinks/Out1', [path '/theta_enc'], ...
    'Port', '2', 'Position', [939 270 969 284]);

wire(path, 'iUVW_A/1', 'Hold phase currents/1');
wire(path, 'Hold phase currents/1', 'U V shunts and INA199/1');
wire(path, 'U V shunts and INA199/1', 'ADC1 two reads and mV/1');
wire(path, 'U V shunts and INA199/2', 'ADC1 two reads and mV/2');
wire(path, 'ADC1 two reads and mV/1', 'Remove offsets and set sign/1');
wire(path, 'ADC1 two reads and mV/2', 'Remove offsets and set sign/2');
wire(path, 'Remove offsets and set sign/1', 'uv_mA/1');
wire(path, 'theta_m_rad/1', 'Hold rotor angle/1');
wire(path, 'Hold rotor angle/1', 'AS5600 angle to code/1');
wire(path, 'AS5600 angle to code/1', 'Raw code to radians/1');
wire(path, 'Raw code to radians/1', 'theta_enc/1');
end
